  var INPUT_CSS = 'width:100%;box-sizing:border-box;padding:.65rem .8rem;border-radius:.8rem;border:1px solid rgba(52,211,153,.6);background:transparent;color:inherit;font:inherit;font-size:1rem;line-height:1.7';
